"""Start the complete local product with one command (Windows, Linux, macOS).

    python ops/dev/run_stack.py            # uses the current interpreter
    python ops/dev/run_stack.py --port 8000
    python ops/dev/run_stack.py --env-file .local/stripe/stripe.env   # e.g. Stripe test keys

Starts, in this order: database migrations, the sample API (flawed on 8800, fixed on 8801,
sharing one key file), the platform demo runner (trusting only those two origins) and the
Django development server. Everything local state lives in ``.local/`` (git-ignored).
Ctrl+C stops every process it started.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCAL = ROOT / ".local"


def read_env_file(path: Path) -> dict[str, str]:
    """``KEY=VALUE`` lines as in docker compose's ``env_file``; blank and ``#`` lines skipped."""
    values = {}
    for number, raw in enumerate(path.read_text("utf-8").splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        name, separator, value = line.partition("=")
        if not separator or not name.strip():
            raise SystemExit(f"{path}:{number}: expected KEY=VALUE")
        values[name.strip()] = value.strip()
    return values


def environment(env_files: list[Path]) -> dict[str, str]:
    env = dict(os.environ)
    for path in env_files:
        loaded = read_env_file(path)
        # Like python-dotenv: a variable already set in the shell wins over the file.
        for name, value in loaded.items():
            env.setdefault(name, value)
        print(f"Loaded {', '.join(sorted(loaded))} from {path}", flush=True)
    paths = [str(ROOT / p) for p in ("src", "sampleapp", "web")]
    env["PYTHONPATH"] = os.pathsep.join([*paths, env.get("PYTHONPATH", "")]).rstrip(os.pathsep)
    env.setdefault("ACCESSGUARD_DEBUG", "1")
    env.setdefault("DATABASE_URL", f"sqlite:///{(LOCAL / 'dev.sqlite3').as_posix()}")
    env.setdefault("ACCESSGUARD_DEMO_FLAWED_ORIGIN", "http://127.0.0.1:8800")
    env.setdefault("ACCESSGUARD_DEMO_FIXED_ORIGIN", "http://127.0.0.1:8801")
    return env


def run(args: list[str], env: dict[str, str]) -> None:
    subprocess.run([sys.executable, *args], cwd=ROOT, env=env, check=True)  # noqa: S603


def start(args: list[str], env: dict[str, str]) -> subprocess.Popen[bytes]:
    return subprocess.Popen([sys.executable, *args], cwd=ROOT, env=env)  # noqa: S603


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--port", type=int, default=8000)
    parser.add_argument(
        "--env-file", type=Path, action="append", default=[],
        help="KEY=VALUE file loaded into the environment (repeatable; the shell wins)",
    )  # fmt: skip
    args = parser.parse_args()
    LOCAL.mkdir(exist_ok=True)
    env = environment(args.env_file)
    manage = str(ROOT / "web" / "manage.py")
    run([manage, "migrate", "--no-input"], env)
    token_file = LOCAL / "demo-runner.token"
    run([manage, "bootstrap_demo_runner", "--token-file", str(token_file)], env)
    credentials = LOCAL / "sampleapp-credentials.json"
    config = LOCAL / "demo-runner.toml"
    config.write_text(
        "# Generated by ops/dev/run_stack.py: the platform demo runner trusts only the demo API.\n"
        f'[control_plane]\nurl = "http://127.0.0.1:{args.port}"\n'
        'token_env = "ACCESSGUARD_RUNNER_TOKEN"\n\n'
        f'[[targets]]\norigin = "{env["ACCESSGUARD_DEMO_FLAWED_ORIGIN"]}"\nzone = "loopback"\n'
        f'credentials_file = "{credentials.name}"\n\n'
        f'[[targets]]\norigin = "{env["ACCESSGUARD_DEMO_FIXED_ORIGIN"]}"\nzone = "loopback"\n'
        f'credentials_file = "{credentials.name}"\n',
        "utf-8",
    )
    processes: list[subprocess.Popen[bytes]] = []
    try:
        sample = ["-m", "accessguard_sampleapp", "serve", "--credentials-out", str(credentials)]
        processes.append(start([*sample, "--variant", "flawed", "--port", "8800"], env))
        time.sleep(1.0)  # the first instance creates the shared key file
        processes.append(start([*sample, "--variant", "fixed", "--port", "8801"], env))
        processes.append(start([manage, "runserver", f"127.0.0.1:{args.port}", "--noreload"], env))
        time.sleep(2.0)
        runner_env = dict(env, ACCESSGUARD_RUNNER_TOKEN=token_file.read_text("utf-8").strip())
        runner = ["-m", "accessguard", "runner", "--config", str(config)]
        processes.append(start(runner, runner_env))
        url = f"http://127.0.0.1:{args.port}/"
        print(f"\nAccessGuard is running on {url}  (Ctrl+C to stop)\n", flush=True)
        while all(p.poll() is None for p in processes):
            time.sleep(0.5)
        print("A process exited; stopping the stack.", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 0
    finally:
        for process in processes:
            if process.poll() is None:
                process.terminate()
        for process in processes:
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()


if __name__ == "__main__":
    sys.exit(main())
